def test_merged_siblings() -> None:
    text = f"## Requisitos\n\n### Presencial\n{words(150, 'p')}\n\n### Virtual\n{words(150, 'v')}\n"
    [only] = chunk([page(text)], size=1800, overlap=150, min_chars=500).chunks
    assert only.heading_path == ["Requisitos"]
    assert only.text.split("\n\n") == ["Presencial", words(150, "p").strip(), "Virtual", words(150, "v").strip()]


