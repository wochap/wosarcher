from itertools import pairwise
from typing import Literal

from wosarcher.models import Page, Source
from wosarcher.stages.chunk import boilerplate, chunk, clean, scoring_text, sections


def page(
    text: str, source_id: str = "s1", page_format: str = "markdown", kind: Literal["web", "file"] = "file"
) -> Page:
    source = Source(source_id=source_id, kind=kind, uri=f"{source_id}.md", title=source_id)
    return Page.model_validate({"source": source, "text": text, "format": page_format})


def words(count: int, seed: str = "w") -> str:
    """`count` characters of distinct words, so no two chunks are duplicates."""
    text = " ".join(f"{seed}{n:04d}" for n in range(count // 6 + 1))
    return text[:count]


def web(text: str, source_id: str = "s1") -> Page:
    return page(text, source_id, kind="web")


def sentences(count: int, seed: str = "w") -> str:
    """About `count` characters of distinct words ending in a full stop."""
    return words(count - 1, seed) + "."


def test_nested_heading_path() -> None:
    found = sections("before\n\n## Results\nr\n\n### Latency\nl\n\n## Other\no\n")
    assert [(s.path, s.text.strip()) for s in found] == [
        ((), "before"),
        (("Results",), "r"),
        (("Results", "Latency"), "l"),
        (("Other",), "o"),
    ]


