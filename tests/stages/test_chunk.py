def test_long_section() -> None:
    result = chunk([page(words(4000))], size=1800, overlap=150, min_chars=500)
    texts = [c.text for c in result.chunks]
    assert len(texts) == 3
    assert all(len(text) <= 1800 for text in texts)
    for previous, current in pairwise(texts):
        assert current[:20] in previous[-150:]


