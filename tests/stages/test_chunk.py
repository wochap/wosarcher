def test_two_short_sections_merge() -> None:
    result = chunk([page(f"# A\n{words(200, 'a')}\n\n# B\n{words(200, 'b')}\n")], size=1800, overlap=150, min_chars=500)
    assert len(result.chunks) == 1
    assert result.chunks[0].heading_path == []
    assert result.chunks[0].text.startswith("A\n\na0000")
    assert "\n\nB\n\nb0000" in result.chunks[0].text


def test_two_sections() -> None:
    result = chunk(
        [page(f"# A\n{words(1000, 'a')}\n\n# B\n{words(1000, 'b')}\n")], size=1800, overlap=150, min_chars=500
    )
    assert [c.heading_path for c in result.chunks] == [["A"], ["B"]]
    assert all("# " not in c.text for c in result.chunks)


