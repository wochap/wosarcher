def test_ids_independent_of_other_pages() -> None:
    alone = chunk([page("# A\none\n\n# B\ntwo\n", "s2")], size=1800, overlap=150, min_chars=0)
    together = chunk(
        [page("# X\nother\n", "s1"), page("# A\none\n\n# B\ntwo\n", "s2")], size=1800, overlap=150, min_chars=0
    )
    assert [c.chunk_id for c in alone.chunks] == [c.chunk_id for c in together.chunks if c.source_id == "s2"]
    assert [c.position for c in alone.chunks] == [0, 1]


def test_same_paragraph_on_two_pages() -> None:
    result = chunk(
        [page("Hello, World! Batteries.", "s1"), page("hello   world -- batteries", "s2")],
        size=1800,
        overlap=150,
        min_chars=500,
    )
    assert [c.source_id for c in result.chunks] == ["s1"]
    assert result.duplicates == 1


def test_scoring_text_context_line() -> None:
    text = scoring_text("Phase 3 trial of drug X", ["Results", "Efficacy"], "Positive in 62% of cases.")
    assert text == "Phase 3 trial of drug X > Results > Efficacy\n\nPositive in 62% of cases."


def test_scoring_text_no_context() -> None:
    assert scoring_text("", [], "Body only.") == "Body only."


def test_scoring_text_long_title() -> None:
    title = " ".join(["word"] * 40)  # 199 characters
    context = scoring_text(title, ["Results"], "Body.").split("\n\n")[0]
    head, path = context.rsplit(" > ", 1)
    assert path == "Results"
    assert len(head) <= 120
    assert title.startswith(head)
    assert head.endswith("word")
